"""Generate Markdown and encyclopedia JSON from the validated content definitions."""

import argparse
import html
import json
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.content import ContentError, DEFAULT_SOURCE, ROOT, load_content
from tools.player_help import DEFAULT_HELP, load_player_help, validate_player_help

REFERENCE_DIRECTORY = Path("docs/reference")
ENCYCLOPEDIA_PATH = Path("generated/encyclopedia.json")
NOTICE = "<!-- Generated by tools/generate_docs.py from canonical content and shared player help. Do not edit. -->"


def _text(value: str) -> str:
    """Treat author text as plain text, including inside Markdown links/tables."""
    escaped = html.escape(" ".join(value.split()), quote=False)
    return re.sub(r"([\\`*{}\[\]()#+\-.!_|])", r"\\\1", escaped)


def _page(lines: list[str], title: str | None = None) -> bytes:
    safe_title = "" if title is None else html.escape(" ".join(title.split()), quote=True)
    metadata = "" if title is None else f"---\ntitle: {json.dumps(safe_title, ensure_ascii=False)}\n---\n\n"
    return (metadata + NOTICE + "\n\n" + "\n".join(lines).rstrip() + "\n").encode("utf-8")


def _links(entities: list[dict], kind: str) -> list[str]:
    return [f"- [{_text(entity['name'])}](../{kind}/{entity['id']}.md)" for entity in entities] or ["None defined."]


def render_outputs(content: dict, player_help: dict | None = None) -> dict[Path, bytes]:
    """Render already-validated content; ordering and bytes do not depend on source order."""
    groups = {kind: sorted(content[kind], key=lambda item: item["id"]) for kind in ("goods", "buildings", "recipes")}
    goods = {item["id"]: item for item in groups["goods"]}
    buildings = {item["id"]: item for item in groups["buildings"]}
    recipes = groups["recipes"]
    help_entries = [] if player_help is None else sorted(
        validate_player_help(player_help, content)["entries"], key=lambda item: item["id"])
    all_entries = {item["id"]: (kind, item)
                   for kind, items in {**groups, "mechanics": help_entries}.items() for item in items}

    def flow(recipe):
        def side(name):
            return " + ".join(f"{item['quantity']} {goods[item['goodId']]['name']}"
                              for item in sorted(recipe[name], key=lambda item: item["goodId"]))
        return f"{side('inputs') or 'No tradeable inputs'} → {side('outputs')}"

    def relationship(recipe):
        return f"{recipe['name']} ({buildings[recipe['buildingId']]['name']}): {flow(recipe)}."

    def related_links(ids):
        return [f"- [{_text(all_entries[entry_id][1]['name'])}](../{all_entries[entry_id][0]}/{entry_id}.md)"
                for entry_id in ids]

    outputs = {}
    encyclopedia = {"formatVersion": 2, "sourceSchemaVersion": content["schemaVersion"],
                    "sourceHelpSchemaVersion": 1}
    index = [
        "# Game reference", "",
        "The same canonical definitions and player explanations power these pages and the offline in-game encyclopedia.", "",
        "Browse [production chains](chains.md), [player mechanics](catalog-mechanics.md), or the categories below.",
        "For a first voyage, start with the [player guide](../PLAYER_GUIDE.md).", "",
        "Recipe quantities are canonical. Construction prices, production intervals, starting assets, and challenge goals come from the active scenario rather than these definitions.", "",
    ]
    chains = ["# Production chains", "",
              "Every relationship below is generated from canonical recipe inputs and outputs. Follow a commodity to see its sources and uses; follow a recipe for exact quantities.", "",
              "| Building | Recipe | Inputs → outputs |", "| --- | --- | --- |"]

    for kind, title in (("goods", "Goods"), ("buildings", "Buildings"), ("recipes", "Recipes")):
        index.extend([f"## {title}", ""])
        index.extend(f"- [{_text(item['name'])}]({kind}/{item['id']}.md)" for item in groups[kind])
        index.append("")
        encyclopedia[kind] = []
        for item in groups[kind]:
            entity_id = item["id"]
            reference = {
                "id": entity_id,
                "name": item["name"],
                "description": item["description"],
                "wikiPath": f"reference/{kind}/{entity_id}.md",
                "paragraphs": [],
                "relatedIds": [],
            }
            page = [
                f"# {_text(item['name'])}", "",
                f"ID: `{entity_id}`", "",
                _text(item["description"]), "",
            ]
            if kind == "goods":
                consumed_by = [recipe for recipe in recipes if any(entry["goodId"] == entity_id for entry in recipe["inputs"])]
                produced_by = [recipe for recipe in recipes if any(entry["goodId"] == entity_id for entry in recipe["outputs"])]
                reference["consumedByRecipeIds"] = [recipe["id"] for recipe in consumed_by]
                reference["producedByRecipeIds"] = [recipe["id"] for recipe in produced_by]
                related_recipes = sorted({recipe["id"]: recipe for recipe in consumed_by + produced_by}.values(),
                                         key=lambda recipe: recipe["id"])
                reference["relatedBuildingIds"] = sorted({recipe["buildingId"] for recipe in related_recipes})
                reference["relatedGoodIds"] = sorted({ingredient["goodId"] for recipe in related_recipes
                                                     for side in ("inputs", "outputs") for ingredient in recipe[side]
                                                     if ingredient["goodId"] != entity_id})
                reference["relatedIds"] = sorted(set(reference["consumedByRecipeIds"] +
                                                    reference["producedByRecipeIds"] +
                                                    reference["relatedBuildingIds"] + reference["relatedGoodIds"]))
                reference["paragraphs"] = [
                    "Production sources: " + ("; ".join(relationship(recipe) for recipe in produced_by) or "None defined."),
                    "Used by: " + ("; ".join(relationship(recipe) for recipe in consumed_by) or "None defined."),
                ]
                page.extend(["## Used as input", "", *_links(consumed_by, "recipes"), ""])
                page.extend(["## Produced as output", "", *_links(produced_by, "recipes"), ""])
                page.extend(["## Related buildings", "", *_links([buildings[entry_id] for entry_id in reference["relatedBuildingIds"]], "buildings"), ""])
                page.extend(["## Production relationships", "", *[f"- {_text(relationship(recipe))}" for recipe in related_recipes], ""])
            elif kind == "buildings":
                building_recipes = [recipe for recipe in recipes if recipe["buildingId"] == entity_id]
                reference["recipeIds"] = [recipe["id"] for recipe in building_recipes]
                reference["inputGoodIds"] = sorted({entry["goodId"] for recipe in building_recipes for entry in recipe["inputs"]})
                reference["outputGoodIds"] = sorted({entry["goodId"] for recipe in building_recipes for entry in recipe["outputs"]})
                reference["relatedIds"] = sorted(set(reference["recipeIds"] + reference["inputGoodIds"] + reference["outputGoodIds"]))
                reference["paragraphs"] = [relationship(recipe) for recipe in building_recipes] + [
                    "Production intervals, construction availability and payments are supplied by the active scenario."]
                page.extend(["## Recipes", "", *_links(building_recipes, "recipes"), ""])
                page.extend(["## Inputs and outputs", "", *[f"- {_text(relationship(recipe))}" for recipe in building_recipes], ""])
                page.extend(["Construction payments, eligibility and production intervals belong to the active scenario.", ""])
            else:
                building = buildings[item["buildingId"]]
                reference["buildingId"] = building["id"]
                recipe_kind = item.get("kind", "transformation")
                reference["kind"] = recipe_kind
                reference["relatedIds"] = sorted({building["id"]} | {
                    ingredient["goodId"] for side in ("inputs", "outputs") for ingredient in item[side]})
                reference["paragraphs"] = [
                    f"Building: {building['name']}. Recipe kind: {recipe_kind}.",
                    flow(item) + ".",
                    "Extraction creates its configured output without tradeable inputs." if recipe_kind == "extraction"
                    else "A complete batch requires every input; a blocked batch consumes nothing.",
                ]
                page.extend([f"Building: [{_text(building['name'])}](../buildings/{building['id']}.md)", ""])
                page.extend([f"Recipe kind: **{recipe_kind}**.", ""])
                for side, heading in (("inputs", "Inputs"), ("outputs", "Outputs")):
                    ingredients = sorted(item[side], key=lambda entry: entry["goodId"])
                    reference[side] = [{"goodId": entry["goodId"], "quantity": entry["quantity"]} for entry in ingredients]
                    if side == "inputs" and recipe_kind == "extraction":
                        page.extend([f"## {heading}", "", "No tradeable inputs. This resource-extraction recipe creates its configured outputs.", ""])
                        continue
                    page.extend([f"## {heading}", "", "| Good | Quantity |", "| --- | ---: |"])
                    for entry in ingredients:
                        good = goods[entry["goodId"]]
                        page.append(f"| [{_text(good['name'])}](../goods/{good['id']}.md) | {entry['quantity']} |")
                    page.append("")
                def chain_side(side):
                    return " + ".join(f"{ingredient['quantity']} [{_text(goods[ingredient['goodId']]['name'])}](goods/{ingredient['goodId']}.md)"
                                      for ingredient in sorted(item[side], key=lambda ingredient: ingredient["goodId"]))
                chains.append(f"| [{_text(building['name'])}](buildings/{building['id']}.md) | [{_text(item['name'])}](recipes/{entity_id}.md) | {chain_side('inputs') or 'No tradeable inputs'} → {chain_side('outputs')} |")
            page.extend(["## Related entries", "", *related_links(reference["relatedIds"]), "",
                         "[Production chains](../chains.md) · [All content](../index.md)", ""])
            outputs[REFERENCE_DIRECTORY / kind / f"{entity_id}.md"] = _page(page, item["name"])
            encyclopedia[kind].append(reference)
        category = [f"# {title}", "", *[f"- [{_text(item['name'])}]({kind}/{item['id']}.md) — {_text(item['description'])}" for item in groups[kind]],
                    "", "[Production chains](chains.md) · [All content](index.md)", ""]
        # Keep catalog pages outside entity namespaces in both Markdown and MkDocs
        # directory URLs: a canonical ID of "index" is valid.
        outputs[REFERENCE_DIRECTORY / f"catalog-{kind}.md"] = _page(category)

    encyclopedia["mechanics"] = []
    help_index = ["# Player mechanics", "",
                  "These explanations are shared with the offline in-game encyclopedia. For exact developer contracts, see [Maintained mechanics](../MECHANICS.md).", ""]
    for item in help_entries:
        reference = {key: item[key] for key in ("id", "name", "description", "paragraphs")}
        reference["relatedIds"] = sorted(item["relatedIds"])
        reference["wikiPath"] = f"reference/mechanics/{item['id']}.md"
        encyclopedia["mechanics"].append(reference)
        help_index.append(f"- [{_text(item['name'])}](mechanics/{item['id']}.md) — {_text(item['description'])}")
        page = [f"# {_text(item['name'])}", "", _text(item["description"]), ""]
        for paragraph in item["paragraphs"]:
            page.extend([_text(paragraph), ""])
        page.extend(["## Related entries", "", *related_links(reference["relatedIds"]), "",
                     "[All player mechanics](../catalog-mechanics.md) · [All content](../index.md)", ""])
        outputs[REFERENCE_DIRECTORY / "mechanics" / f"{item['id']}.md"] = _page(page, item["name"])
    index.extend(["## Player mechanics", "", "[Browse shared gameplay explanations](catalog-mechanics.md).", ""])
    outputs[REFERENCE_DIRECTORY / "catalog-mechanics.md"] = _page(help_index)
    outputs[REFERENCE_DIRECTORY / "chains.md"] = _page(chains)
    outputs[REFERENCE_DIRECTORY / "index.md"] = _page(index)
    outputs[ENCYCLOPEDIA_PATH] = (json.dumps(encyclopedia, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    return outputs


def synchronize(outputs: dict[Path, bytes], root: Path, *, check: bool) -> list[str]:
    """Check or refresh owned files; all files under docs/reference are generated."""
    root = root.resolve()
    reference_root = root / REFERENCE_DIRECTORY
    owned = {path.relative_to(root) for path in reference_root.rglob("*") if path.is_file()}
    if (root / ENCYCLOPEDIA_PATH).exists():
        owned.add(ENCYCLOPEDIA_PATH)
    differences = []
    for relative in sorted(owned - outputs.keys()):
        differences.append(f"Unexpected generated file: {relative.as_posix()}")
        if not check:
            target = root / relative
            if not target.resolve().is_relative_to(reference_root.resolve()):
                raise ContentError(f"Generated file escapes its owned directory: {relative}")
            target.unlink()
    for relative, expected in sorted(outputs.items()):
        target = root / relative
        if not target.exists():
            differences.append(f"Missing generated file: {relative.as_posix()}")
        elif target.read_bytes() != expected:
            differences.append(f"Changed generated file: {relative.as_posix()}")
        else:
            continue
        if not check:
            if not target.resolve().is_relative_to(root):
                raise ContentError(f"Generated file escapes the repository: {relative}")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected)
    return differences


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--help-source", type=Path, default=DEFAULT_HELP)
    parser.add_argument("--check", action="store_true", help="Fail for missing, changed, or unexpected generated files; never write.")
    args = parser.parse_args()
    try:
        content = load_content(args.source)
        outputs = render_outputs(content, load_player_help(content, args.help_source))
        differences = synchronize(outputs, ROOT, check=args.check)
    except (ContentError, OSError, UnicodeError) as error:
        print(f"Reference generation failed: {error}", file=sys.stderr)
        return 1
    if args.check and differences:
        print("\n".join(differences), file=sys.stderr)
        print("Run python tools/generate_docs.py to refresh the generated reference.", file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} reference files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
